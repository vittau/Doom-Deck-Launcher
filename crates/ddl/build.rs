//! Compiles the `.slint` user interface into Rust at build time (spec 001,
//! R1/R4) and indexes the bundled mapset screenshots (spec 023, R2).
//!
//! `slint_build::compile` embeds the generated code through
//! `slint::include_modules!()` in `src/main.rs`; rerun tracking for the
//! `.slint` file is handled by slint-build.
//!
//! `embed_resources(EmbedFiles)` embeds every file the `.slint` references with
//! `@image-url`, so the committed screenshots under `ui/assets/screenshots/`
//! ship inside the binary and show offline. This script additionally writes a
//! `(recipe id, asset paths)` index (`$OUT_DIR/screenshots.rs`, consumed by
//! `src/screenshots.rs`) so Rust code and tests can see which screenshots belong
//! to which recipe without duplicating the directory listing by hand.

use std::env;
use std::fs;
use std::path::PathBuf;

fn main() {
    let lookup = write_screenshot_index();
    slint_build::compile_with_config(
        "ui/app-window.slint",
        slint_build::CompilerConfiguration::new()
            .embed_resources(slint_build::EmbedResourcesKind::EmbedFiles)
            .with_library_paths(std::collections::HashMap::from([(
                "screenshots".into(),
                lookup,
            )])),
    )
    .expect("failed to compile ui/app-window.slint");
}

/// Writes `$OUT_DIR/screenshots.rs`: one `(recipe id, &[asset path])` entry per
/// directory under `ui/assets/screenshots/`, asset paths relative to this crate
/// (the `.slint` asset root), sorted for a stable build.
fn write_screenshot_index() -> PathBuf {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let root = manifest.join("ui/assets/screenshots");
    println!("cargo:rerun-if-changed={}", root.display());

    let mut entries: Vec<(String, Vec<String>)> = Vec::new();
    let mut credit_sets: Vec<(String, Vec<String>)> = Vec::new();
    if let Ok(dirs) = fs::read_dir(&root) {
        for dir in dirs.flatten() {
            let path = dir.path();
            if !path.is_dir() {
                continue;
            }
            let Some(id) = path.file_name().and_then(|name| name.to_str()) else {
                continue;
            };
            let mut assets: Vec<String> = fs::read_dir(&path)
                .into_iter()
                .flatten()
                .flatten()
                .filter_map(|entry| entry.file_name().to_str().map(str::to_owned))
                .filter(|name| {
                    matches!(
                        name.rsplit('.')
                            .next()
                            .map(str::to_ascii_lowercase)
                            .as_deref(),
                        Some("png" | "jpg" | "jpeg" | "webp")
                    )
                })
                .map(|name| format!("assets/screenshots/{id}/{name}"))
                .collect();
            assets.sort();
            if !assets.is_empty() {
                entries.push((id.to_owned(), assets));
                credit_sets.push((id.to_owned(), source_credits(&path.join("SOURCES.toml"))));
            }
        }
    }
    entries.sort();
    // Recipe-id order, so the generated list is stable whatever the directory order.
    credit_sets.sort();
    let mut credits: Vec<String> = Vec::new();
    for credit in credit_sets.into_iter().flat_map(|(_, set)| set) {
        if !credits.contains(&credit) {
            credits.push(credit);
        }
    }

    let mut code = String::from(
        "// Generated by crates/ddl/build.rs — do not edit.\n\
         /// Bundled mapset screenshots per recipe id (spec 023, R2), asset paths\n\
         /// relative to the `ui/` asset root. First directory entry is\n\
         /// the card image.\n\
         pub static EMBEDDED_SCREENSHOTS: &[(&str, &[&str])] = &[\n",
    );
    for (id, assets) in &entries {
        code.push_str(&format!("    ({id:?}, &[\n"));
        for asset in assets {
            code.push_str(&format!("        {asset:?},\n"));
        }
        code.push_str("    ]),\n");
    }
    code.push_str("];\n");
    code.push_str(
        "/// Distinct screenshot credits from every bundled `SOURCES.toml` (spec 033, R4).\n\
         pub static SCREENSHOT_CREDITS: &[&str] = &[\n",
    );
    for credit in &credits {
        code.push_str(&format!("    {credit:?},\n"));
    }
    code.push_str("];\n");

    let out = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR")).join("screenshots.rs");
    write_if_changed(&out, &code);

    // Literal URLs let Slint embed/decode the assets with its existing image support.
    // Selection still follows the recipe's declared first asset, not directory order.
    let mut lookup = String::from(
        "export global ScreenshotAssets {\n    public pure function image(asset: string) -> image {\n",
    );
    for (_, assets) in &entries {
        for asset in assets {
            let absolute = manifest.join("ui").join(asset);
            lookup.push_str(&format!(
                "        if (asset == {asset:?}) {{ return @image-url({:?}); }}\n",
                absolute.to_str().expect("UTF-8 asset path")
            ));
        }
    }
    lookup.push_str("        return @image-url(\"\");\n    }\n}\n");
    let path = out.with_file_name("screenshots.slint");
    write_if_changed(&path, &lookup);
    path
}

/// The `credit = "..."` values of a `SOURCES.toml` (one basic string per line, as
/// the files are written); an unreadable file contributes none and the catalog
/// lint reports it.
fn source_credits(path: &std::path::Path) -> Vec<String> {
    let Ok(text) = fs::read_to_string(path) else {
        return Vec::new();
    };
    text.lines()
        .filter_map(|line| line.strip_prefix("credit = \""))
        .filter_map(|rest| rest.strip_suffix('"'))
        .map(|raw| raw.replace("\\\"", "\"").replace("\\\\", "\\"))
        .collect()
}

// The compiler tracks the generated Slint import. Preserve its mtime when the
// lookup is unchanged so it does not retrigger the build on every cargo command.
fn write_if_changed(path: &std::path::Path, contents: &str) {
    if fs::read_to_string(path).ok().as_deref() != Some(contents) {
        fs::write(path, contents).expect("write generated screenshot index");
    }
}
