#!/usr/bin/env python3
"""Author Ember Cathedral bronze frames. Python stdlib only; no raster inputs.

The 28px profile is shared by all four mitered rails and the corner grounds.
Carving stays inside the corners, never across the 28px piece boundaries.
Run with --check to verify byte-identical production SVGs.
"""
import argparse
from pathlib import Path
from xml.etree import ElementTree

OUT = Path(__file__).resolve().parent
PROFILE = [(0, '#140d0f'), (1, '#302021'), (2, '#80533b'),
           (3, '#36231e'), (4, '#1a1114'), (6, '#2a1c1e'),
           (7, '#79503a'), (8, '#9d6945'), (9, '#412b22'),
           (10, '#140d10'), (12, '#503329'), (13, '#a47750'),
           (14, '#68422f'), (15, '#211313'), (16, '#451e1b'),
           (18, '#60261e'), (19, '#732e22'), (20, '#462018'),
           (22, '#2a1515'), (23, '#a07550'), (24, '#6d4732'),
           (25, '#341f1b'), (26, '#150d0e'), (27, '#211719')]


def path(d, fill, stroke='', width=.65):
    return f'<path d="{d}" fill="{fill}"' + (f' stroke="{stroke}" stroke-width="{width}" stroke-linecap="round" stroke-linejoin="round"' if stroke else '') + '/>'


def svg(w, h, body):
    return (f'<svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="{h}" viewBox="0 0 {w} {h}">\n'
            '<!-- Generated by author_frame.py; original geometric bronze carving. -->\n'
            '<defs><linearGradient id="bronze" x1="0" y1="0" x2="0.7" y2="1"><stop stop-color="#b8865e"/><stop offset=".35" stop-color="#815137"/><stop offset=".65" stop-color="#311c18"/><stop offset="1" stop-color="#885138"/></linearGradient></defs>\n' + body + '\n</svg>\n')


def profile(w, h):
    body = ''
    for i, (d, color) in enumerate(PROFILE):
        e = PROFILE[i+1][0] if i+1 < len(PROFILE) else 28
        # An opposite-winding ring has a true miter: identical distance to both rails.
        body += path(f'M{d} {d}H{w-d}V{h-d}H{d}Z M{e} {e}V{h-e}H{w-e}V{e}Z', color)
    return body


def corner():
    # A heavy, stepped bronze casting, with incised nested elbow and screw boss.
    b = path('M2 2H19V5H24V12H22V24H12V22H5V19H2Z', '#1b1112', '#6b4431', .8)
    b += path('M3 3H18V6H23V11H20V23H13V20H6V18H3Z', 'url(#bronze)', '#b38055', .6)
    b += path('M5 5H16V8H21V10H18V21H15V18H8V16H5Z', '#37211a', '#4c2e22', .6)
    b += path('M6 6H15V9H20 M6 6V15H9V20', 'none', '#be8b61', .65)
    b += path('M9 10L16 13 13 16Z M18 18L22 20 20 22Z', 'url(#bronze)', '#291713', .7)
    b += path('M13 13L21 21M15 13L22 20M13 15L20 22', 'none', '#342019', .5)
    b += '<circle cx="8.5" cy="8.5" r="2.4" fill="#261614" stroke="#b37c51" stroke-width=".6"/>'
    b += path('M7 7L10 10', 'none', '#8f5b3b', .65)
    return b


def ornament(length):
    # Pointed gothic buttresses, incised lancet arches and an oxblood recess.
    # The SVG has no ground: the shared rail below stays bit-identical at fit.
    c = length / 2
    span = 42 if length == 96 else 21
    b = ''
    for flip in (False, True):
        wing = path(f'M{c} 4L{c-span} 12L{c-span+8} 14V20L{c-15} 18V26H{c}Z', '#1b1112', '#754b35', .65)
        wing += path(f'M{c-2} 6L{c-span+2} 12L{c-20} 12V23L{c-15} 24V15L{c-5} 11V27H{c-2}Z', 'url(#bronze)', '#ae7850', .45) if length == 96 else path(f'M{c-2} 6L{c-span+2} 12L{c-14} 13V20L{c-9} 22V12L{c-3} 10Z', 'url(#bronze)', '#ae7850', .45)
        if length == 96:
            wing += path(f'M{c-30} 13L{c-25} 10V20L{c-30} 19Z M{c-40} 12L{c-32} 14V17L{c-40} 16Z', '#5e3526', '#9b6745', .45)
            wing += path(f'M{c-19} 25V17L{c-14} 11 {c-9} 16V27Z', '#271315', '#a36b46', .6)
            wing += path(f'M{c-16} 25V18L{c-14} 15 {c-12} 18V26Z', '#6c2c22')
            wing += path(f'M{c-24} 12V19M{c-34} 13V16', 'none', '#291714', .7)
        b += f'<g transform="translate({length if flip else 0} 0) scale({-1 if flip else 1} 1)">{wing}</g>'
    b += path(f'M{c} 1L{c+8} 6V27H{c-8}V6Z', '#211315', '#b17a50', .65)
    b += path(f'M{c} 2L{c+5} 7V27H{c}Z', 'url(#bronze)')
    b += path(f'M{c-5} 27V7L{c} 2V27Z', '#805039', '#c18b5d', .4)
    b += path(f'M{c-3} 27V11L{c} 6 {c+3} 11V27Z', '#211214', '#4d291e', .5)
    b += path(f'M{c} 8V26', 'none', '#a46642', .65)
    return b


def assets():
    b = profile(128, 128) + path('M28 28H100V100H28Z', '#211719')
    for x, y, sx, sy in [(0, 0, 1, 1), (128, 0, -1, 1), (0, 128, 1, -1), (128, 128, -1, -1)]:
        b += f'<g transform="translate({x} {y}) scale({sx} {sy})">{corner()}</g>'
    result = {}
    # Each slice has its own intrinsic canvas, so Slint rasterizes corners at
    # their physical size, rather than shrinking a full SVG for each slice.
    boxes = {'top-left': (0, 0, 28, 28), 'top-right': (100, 0, 28, 28),
             'bottom-left': (0, 100, 28, 28), 'bottom-right': (100, 100, 28, 28),
             'top': (28, 0, 72, 28), 'bottom': (28, 100, 72, 28),
             'left': (0, 28, 28, 72), 'right': (100, 28, 28, 72)}
    for name, (x, y, w, h) in boxes.items():
        result[f'frame-{name}.svg'] = svg(w, h, f'<g transform="translate({-x} {-y})">{b}</g>')
    for name, length in [('top', 96), ('bottom', 96), ('left', 48), ('right', 48)]:
        # Undistorted carving with transparency in the existing ornament box.
        art = ornament(length)
        transforms = {'top': '', 'bottom': 'translate(0 28) scale(1 -1)', 'left': 'translate(0 48) rotate(-90)', 'right': 'translate(28 0) rotate(90)'}
        if transforms[name]:
            art = f'<g transform="{transforms[name]}">{art}</g>'
        w, h = (length, 28) if name in ('top', 'bottom') else (28, length)
        result[f'ornament-{name}.svg'] = svg(w, h, art)
    return result


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for name, content in assets().items():
        allowed = {'svg', 'defs', 'linearGradient', 'stop', 'path', 'g', 'circle'}
        tree = ElementTree.fromstring(content)
        assert all(node.tag.rsplit('}', 1)[-1] in allowed for node in tree.iter())
        assert all(not key.endswith('href') for node in tree.iter() for key in node.attrib)
        destination = OUT / name
        if args.check:
            assert destination.read_bytes() == content.encode(), f'stale SVG: {name}'
        else:
            destination.write_text(content)
        print(name)
